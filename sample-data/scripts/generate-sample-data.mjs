/** 生年月日から元号コードを求める（1:明治 2:大正 3:昭和 4:平成 5:令和） */
function 元号コード(ymd) {
  if (ymd >= '2019-05-01') return 5;
  if (ymd >= '1989-01-08') return 4;
  if (ymd >= '1926-12-25') return 3;
  if (ymd >= '1912-07-30') return 2;
  return 1;
}

function 年齢(生年月日, 基準日 = AS_OF) {
  const [by, bm, bd] = 生年月日.split('-').map(Number);
  const [ay, am, ad] = 基準日.split('-').map(Number);
  let age = ay - by;
  if (am < bm || (am === bm && ad < bd)) age -= 1;
  return age;
}

