function validate() {
  const errors = [];
  const names = COLUMNS.map(([n]) => n);

  // 個人番号カラムが混入していないこと（Issue #4 の合意事項）
  if (names.some(n => n === '個人番号' || n.includes('マイナンバー'))) {
    errors.push('個人番号に相当するカラムが定義に含まれている');
  }
  // 団体コードが架空値のみであること
  for (const r of rows) {
    if (r['市区町村コード'] !== MUNI_CODE || r['住所_市区町村コード'] !== MUNI_CODE) {
      errors.push(`宛名番号 ${r['宛名番号']}: 自団体コードが ${MUNI_CODE} ではない`);
    }
    for (const key of ['転入前住所_市区町村コード', '転出先住所（確定）_市区町村コード', '本籍_市区町村コード']) {
      const v = String(r[key] ?? '');
      if (v && v !== String(MUNI_CODE) && v !== OTHER_MUNI_CODE) {
        errors.push(`宛名番号 ${r['宛名番号']}: ${key} が架空の団体コードではない (${v})`);
      }
    }
  }
  // 宛名番号の一意性
  const ids = new Set();
  for (const r of rows) {
    if (ids.has(r['宛名番号'])) errors.push(`宛名番号が重複: ${r['宛名番号']}`);
    ids.add(r['宛名番号']);
  }
  // 世帯ごとの整合性: 記載順位1が世帯主(続柄コード1=2)で、世帯主氏名が全員一致すること
  const byHousehold = new Map();
  for (const r of rows) {
    if (!byHousehold.has(r['世帯番号'])) byHousehold.set(r['世帯番号'], []);
    byHousehold.get(r['世帯番号']).push(r);
  }
  for (const [hcode, members] of byHousehold) {
    const heads = members.filter(r => r['続柄コード1'] === 2);
    if (heads.length !== 1) errors.push(`世帯 ${hcode}: 世帯主が ${heads.length} 人`);
    const orders = members.map(r => r['記載順位']).sort((a, b) => a - b);
    if (orders.some((v, i) => v !== i + 1)) errors.push(`世帯 ${hcode}: 記載順位が連番でない`);
    const headName = heads[0]?.['氏名'];
    if (members.some(r => r['世帯主氏名'] !== headName)) {
      errors.push(`世帯 ${hcode}: 世帯主氏名が世帯主の氏名と一致しない`);
    }
  }
  // 続柄表記が対応表に存在すること
  for (const r of rows) {
    if (!r['続柄表記']) errors.push(`宛名番号 ${r['宛名番号']}: 続柄コード1=${r['続柄コード1']} に対応する続柄表記がない`);
  }
  return errors;
}

const errors = validate();
if (errors.length > 0) {
  console.error('サンプルデータの検証に失敗しました:');
  for (const e of errors) console.error('  - ' + e);
  process.exit(1);
}

